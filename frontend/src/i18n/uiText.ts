/**
 * @brief 把一条中文 UI 文案翻成当前界面语言。
 * @param message 中文原文（同时作为词典键）
 * @param vars 按 `{0}` `{1}` 顺序替换的参数；缺省则不插值
 */
export function tx(message: string, vars?: ReadonlyArray<string | number | null | undefined>): string {
  const language = (i18n.language || 'zh').toLowerCase()
  const template = language.startsWith('en') ? (UI_EN[message] ?? message) : message
  if (!vars || vars.length === 0) return template
  return template.replace(/\{(\d+)\}/g, (match, index) => {
    const value = vars[Number(index)]
    // null / undefined 保留占位符原样，调用方少写一层兜底也不会显示成 "undefined"
    return value === undefined || value === null ? match : String(value)
  })
}

/**
 * @brief 组件内使用：随语言切换自动重算。
 * @details 内部依赖 `useTranslation()` 的订阅，语言一变组件就会重渲染，
 *          因此返回值不需要调用方额外缓存。
 */
export function useUiText() {
  const { i18n: instance } = useTranslation()
  return useCallback(
    (message: string, vars?: ReadonlyArray<string | number | null | undefined>) => tx(message, vars),
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [instance.language],
  )
}
