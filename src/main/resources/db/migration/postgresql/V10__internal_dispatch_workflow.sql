CREATE TABLE audit_orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    structure_id INTEGER NOT NULL,
    order_code TEXT NOT NULL,
    customer_name TEXT NOT NULL DEFAULT '',
    project_name TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'DRAFT',
    priority INTEGER NOT NULL DEFAULT 3,
    owner_name TEXT NOT NULL DEFAULT '',
    notes TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    version INTEGER NOT NULL DEFAULT 0,
    UNIQUE (structure_id, order_code),
    FOREIGN KEY (structure_id) REFERENCES structures(id) ON DELETE CASCADE
);

CREATE TABLE audit_order_phases (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_order_id INTEGER NOT NULL,
    phase_code TEXT NOT NULL,
    phase_name TEXT NOT NULL,
    start_time TEXT NOT NULL,
    end_time TEXT NOT NULL,
    location_id INTEGER NOT NULL,
    required_headcount INTEGER NOT NULL DEFAULT 1,
    lead_required INTEGER NOT NULL DEFAULT 0 CHECK (lead_required IN (0, 1)),
    continuity_group TEXT NOT NULL DEFAULT '',
    delivery_mode TEXT NOT NULL DEFAULT 'ONSITE',
    status TEXT NOT NULL DEFAULT 'PLANNED',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    version INTEGER NOT NULL DEFAULT 0,
    UNIQUE (audit_order_id, phase_code),
    FOREIGN KEY (audit_order_id) REFERENCES audit_orders(id) ON DELETE CASCADE,
    FOREIGN KEY (location_id) REFERENCES locations(id) ON DELETE RESTRICT
);

CREATE TABLE audit_phase_skills (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phase_id INTEGER NOT NULL,
    skill_id INTEGER NOT NULL,
    minimum_count INTEGER NOT NULL DEFAULT 1,
    lead_only INTEGER NOT NULL DEFAULT 0 CHECK (lead_only IN (0, 1)),
    UNIQUE (phase_id, skill_id, lead_only),
    FOREIGN KEY (phase_id) REFERENCES audit_order_phases(id) ON DELETE CASCADE,
    FOREIGN KEY (skill_id) REFERENCES skills(id) ON DELETE RESTRICT
);

ALTER TABLE shifts ADD COLUMN audit_order_phase_id INTEGER;
ALTER TABLE shifts ADD COLUMN published_plan_id INTEGER;
ALTER TABLE shifts ADD COLUMN required_role TEXT NOT NULL DEFAULT 'AUDITOR';

CREATE TABLE schedule_plans (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    structure_id INTEGER NOT NULL,
    name TEXT NOT NULL,
    window_start TEXT NOT NULL,
    window_end TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'DRAFT',
    revision INTEGER NOT NULL DEFAULT 1,
    parent_plan_id INTEGER,
    solver_score TEXT,
    created_by TEXT NOT NULL,
    submitted_by TEXT,
    approved_by TEXT,
    published_by TEXT,
    rejection_reason TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    submitted_at TEXT,
    approved_at TEXT,
    published_at TEXT,
    version INTEGER NOT NULL DEFAULT 0,
    FOREIGN KEY (structure_id) REFERENCES structures(id) ON DELETE CASCADE,
    FOREIGN KEY (parent_plan_id) REFERENCES schedule_plans(id) ON DELETE SET NULL
);

CREATE TABLE schedule_plan_assignments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id INTEGER NOT NULL,
    shift_id INTEGER NOT NULL,
    phase_id INTEGER,
    slot_index INTEGER NOT NULL DEFAULT 1,
    employee_id INTEGER,
    locked INTEGER NOT NULL DEFAULT 0 CHECK (locked IN (0, 1)),
    assignment_role TEXT NOT NULL DEFAULT 'AUDITOR',
    risk_code TEXT NOT NULL DEFAULT '',
    change_reason TEXT NOT NULL DEFAULT '',
    shift_version INTEGER NOT NULL DEFAULT 0,
    employee_status_updated_at TEXT NOT NULL DEFAULT '',
    UNIQUE (plan_id, shift_id),
    FOREIGN KEY (plan_id) REFERENCES schedule_plans(id) ON DELETE CASCADE,
    FOREIGN KEY (shift_id) REFERENCES shifts(id) ON DELETE CASCADE,
    FOREIGN KEY (phase_id) REFERENCES audit_order_phases(id) ON DELETE SET NULL,
    FOREIGN KEY (employee_id) REFERENCES employees(id) ON DELETE SET NULL
);

CREATE TABLE import_jobs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token TEXT NOT NULL UNIQUE,
    structure_id INTEGER NOT NULL,
    file_name TEXT NOT NULL,
    file_sha256 TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'PREVIEW',
    row_count INTEGER NOT NULL DEFAULT 0,
    error_count INTEGER NOT NULL DEFAULT 0,
    warning_count INTEGER NOT NULL DEFAULT 0,
    summary_json TEXT NOT NULL DEFAULT '{}',
    payload_json TEXT NOT NULL DEFAULT '{}',
    errors_json TEXT NOT NULL DEFAULT '[]',
    created_by TEXT NOT NULL,
    created_at TEXT NOT NULL,
    confirmed_by TEXT,
    confirmed_at TEXT,
    FOREIGN KEY (structure_id) REFERENCES structures(id) ON DELETE CASCADE
);

CREATE TABLE audit_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    structure_id INTEGER,
    actor TEXT NOT NULL,
    action TEXT NOT NULL,
    entity_type TEXT NOT NULL,
    entity_id TEXT NOT NULL DEFAULT '',
    details_json TEXT NOT NULL DEFAULT '{}',
    created_at TEXT NOT NULL,
    FOREIGN KEY (structure_id) REFERENCES structures(id) ON DELETE SET NULL
);

CREATE INDEX idx_audit_orders_structure_status ON audit_orders(structure_id, status);
CREATE INDEX idx_audit_phases_order_start ON audit_order_phases(audit_order_id, start_time);
CREATE INDEX idx_phase_skills_phase ON audit_phase_skills(phase_id);
CREATE INDEX idx_shifts_phase ON shifts(audit_order_phase_id);
CREATE INDEX idx_plans_structure_status ON schedule_plans(structure_id, status, updated_at);
CREATE INDEX idx_plan_assignments_plan ON schedule_plan_assignments(plan_id);
CREATE INDEX idx_import_jobs_structure_created ON import_jobs(structure_id, created_at);
CREATE INDEX idx_audit_events_structure_created ON audit_events(structure_id, created_at);
