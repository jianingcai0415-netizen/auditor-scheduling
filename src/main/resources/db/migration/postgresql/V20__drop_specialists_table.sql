-- Elimina definitivamente locations.specialist_id e la tabella specialists.
-- Gemella della migrazione SQLite di pari versione: stessa semantica, sintassi nativa.
--
-- V17 ha svuotato specialists e ha azzerato locations.specialist_id, ma non ha potuto
-- togliere ne' la colonna ne' la tabella: PostgreSQL rifiuta DROP TABLE finche' una chiave
-- esterna la referenzia, e su SQLite ALTER TABLE ... DROP COLUMN non e' ammesso per una
-- colonna che compare in un vincolo di chiave esterna della tabella stessa.
-- La colonna era l'unico anello che teneva in vita la tabella.
--
-- Ricostruzione in parallelo alla gemella SQLite (stessa forma di V5 per skills): il
-- contratto delle due tabelle deve restare identico dopo la normalizzazione, come
-- verificato da MigrationSchemaParityTest.

CREATE TABLE locations_new (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    l_order INTEGER,
    code TEXT UNIQUE,
    structure_id INTEGER NOT NULL DEFAULT 1,
    active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
    latitude REAL,
    longitude REAL,
    FOREIGN KEY (structure_id) REFERENCES structures(id) ON DELETE CASCADE
);

-- Copia integrale: gli id sono referenziati dalle tabelle figlie e devono restare quelli.
INSERT INTO locations_new (id, name, l_order, code, structure_id, active, latitude, longitude)
SELECT id, name, l_order, code, structure_id, active, latitude, longitude FROM locations;

-- Gli id espliciti qui sopra non fanno avanzare la sequenza identity: senza questo
-- riallineamento il primo insert successivo riuserebbe un id gia' occupato.
-- Si usa setval(MAX(id)) invece della forma letterale "ALTER COLUMN id RESTART WITH n"
-- usata da V1/V14 perche' qui gli id sono dati utente, non seed deterministico: un numero
-- scritto a mano sarebbe sbagliato su qualunque database con id massimo diverso dal nostro.
-- setval(seq, n) fa restituire n+1 al prossimo nextval, che e' esattamente l'id libero.
SELECT setval(pg_get_serial_sequence('locations_new', 'id'),
              COALESCE((SELECT MAX(id) FROM locations_new), 1));

-- CASCADE e' obbligatorio: PostgreSQL non lascia eliminare una tabella referenziata.
-- Porta pero' via anche le sei chiavi esterne che puntavano a locations, ricreate sotto
-- dopo la rinomina. Su SQLite il problema non si pone: i vincoli stanno nel corpo delle
-- tabelle figlie e la rinomina li fa tornare validi.
DROP TABLE locations CASCADE;
ALTER TABLE locations_new RENAME TO locations;

-- L'indice muore con la tabella: va ricreato con lo stesso nome.
CREATE INDEX IF NOT EXISTS idx_locations_structure ON locations(structure_id);

-- Vincoli identici a quelli di V1, che erano privi di ON DELETE (quindi NO ACTION).
ALTER TABLE location_skills ADD CONSTRAINT location_skills_location_id_fkey
    FOREIGN KEY (location_id) REFERENCES locations(id);
ALTER TABLE shifts ADD CONSTRAINT shifts_location_id_fkey
    FOREIGN KEY (location_id) REFERENCES locations(id);
ALTER TABLE shift_templates ADD CONSTRAINT shift_templates_location_id_fkey
    FOREIGN KEY (location_id) REFERENCES locations(id);
ALTER TABLE audit_order_phases ADD CONSTRAINT audit_order_phases_location_id_fkey
    FOREIGN KEY (location_id) REFERENCES locations(id);
ALTER TABLE travel_time_matrix ADD CONSTRAINT travel_time_matrix_to_location_id_fkey
    FOREIGN KEY (to_location_id) REFERENCES locations(id);
ALTER TABLE travel_time_matrix ADD CONSTRAINT travel_time_matrix_from_location_id_fkey
    FOREIGN KEY (from_location_id) REFERENCES locations(id);

-- Ormai non piu' referenziata da nessuno: nessun CASCADE necessario.
DROP TABLE IF EXISTS specialists;
