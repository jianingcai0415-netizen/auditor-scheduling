-- Le coordinate della cache tornano a essere double precision (8 byte), come su SQLite.
--
-- V21 ha creato questa tabella con colonne REAL in entrambe le migrazioni, ma "REAL" non
-- significa la stessa cosa nei due motori: su SQLite e' un double a 8 byte, su PostgreSQL
-- e' un float a 4 byte. Hibernate mappa i campi dell'entita' come double e quindi lega i
-- parametri come float8: salvando 31.2304 la colonna REAL trattiene 31.230400085449219,
-- e il successivo "WHERE from_lat = ?" non trova piu' la riga. L'upsert di
-- TravelMatrixStore (prima DELETE, poi INSERT) degenera in un puro INSERT e viola il
-- vincolo UNIQUE: la scrittura della cache fallisce del tutto su PostgreSQL.
--
-- Qui la tabella viene ricostruita con DOUBLE PRECISION, e i valori esistenti vengono
-- riportati a 5 decimali prima di essere copiati, altrimenti le righe gia' scritte
-- conserverebbero il rumore dei 4 byte e continuerebbero a non essere trovate.
--
-- Il ricostruisci-e-rinomina e' lo stesso schema di V21 (SQLite non sa cambiare il tipo di
-- una colonna): le due migrazioni gemelle restano cosi' confrontabili una a una.

CREATE TABLE travel_time_matrix_v27 (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_lat DOUBLE PRECISION NOT NULL,
    from_lon DOUBLE PRECISION NOT NULL,
    to_lat DOUBLE PRECISION NOT NULL,
    to_lon DOUBLE PRECISION NOT NULL,
    minutes INTEGER NOT NULL,
    distance_meters INTEGER,
    computed_at TEXT NOT NULL,
    UNIQUE (from_lat, from_lon, to_lat, to_lon),
    CHECK (from_lat <> to_lat OR from_lon <> to_lon)
);

-- Gli id non vengono copiati: nessuna riga vi fa riferimento (la chiave della cache e' la
-- coppia di coordinate) e lasciarli rigenerare evita di dover riallineare la sequenza
-- identity, che SQLite non ha.
INSERT INTO travel_time_matrix_v27 (from_lat, from_lon, to_lat, to_lon, minutes, distance_meters, computed_at)
SELECT
    ROUND(CAST(from_lat AS numeric), 5),
    ROUND(CAST(from_lon AS numeric), 5),
    ROUND(CAST(to_lat AS numeric), 5),
    ROUND(CAST(to_lon AS numeric), 5),
    minutes, distance_meters, computed_at
FROM travel_time_matrix;

DROP TABLE travel_time_matrix;
ALTER TABLE travel_time_matrix_v27 RENAME TO travel_time_matrix;

CREATE INDEX IF NOT EXISTS idx_travel_time_computed ON travel_time_matrix(computed_at);
